-- speeding up LocalPlayer
do
    local _LocalPlayer = LocalPlayer
    local client

    function LocalPlayer()
        client = _LocalPlayer()
        if IsValid( client ) then
            LocalPlayer = function() return client end
        end
        return client
    end
end

